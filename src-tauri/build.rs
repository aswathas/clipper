use std::{
    env, fs,
    path::{Path, PathBuf},
};

fn main() {
    tauri_build::build();
    embed_ui();
}

/// Embed `../src/ui` as a route table.
///
/// The desktop app is headless: this directory *is* the product's only UI, served
/// over HTTP by `server.rs`. Embedding the whole directory rather than a
/// hand-maintained list of files means adding a component to the web app needs no
/// Rust change — a missing whitelist entry would otherwise 404 silently.
fn embed_ui() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let ui = manifest
        .parent()
        .expect("src-tauri has a parent")
        .join("src")
        .join("ui");
    println!("cargo:rerun-if-changed={}", ui.display());

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    collect(&ui, &ui, &mut entries);
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let mut code = String::from(
        "// @generated by build.rs — do not edit.\n\
         // (route, content-type, bytes) for every file under src/ui\n\
         pub static UI_ASSETS: &[(&str, &str, &[u8])] = &[\n",
    );
    for (route, path) in &entries {
        // A native path here; `{:?}` escapes Windows separators correctly.
        let file = path.to_string_lossy().into_owned();
        code.push_str(&format!(
            "    ({route:?}, {:?}, include_bytes!({file:?})),\n",
            mime_for(route)
        ));
        println!("cargo:rerun-if-changed={}", path.display());
    }
    code.push_str("];\n");

    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("ui_assets.rs");
    fs::write(&out, code).expect("write ui_assets.rs");
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
            continue;
        }
        if !path.is_file() {
            continue;
        }
        let relative = path
            .strip_prefix(root)
            .unwrap_or(&path)
            .to_string_lossy()
            .replace('\\', "/");
        out.push((format!("/{relative}"), path));
    }
}

fn mime_for(route: &str) -> &'static str {
    match route.rsplit('.').next().unwrap_or_default() {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" | "webmanifest" => "application/json; charset=utf-8",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "txt" => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}
